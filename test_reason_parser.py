def run_test():
    for type_name, samples in SAMPLES.items():
        print(f"\n{'='*20} {type_name} {'='*20}\n")
        for i, sample in enumerate(samples, 1):
            print(f"--- Sample {i} ---")
            print(f"[Input]:\n{sample[:100]}..." if len(sample) > 100 else f"[Input]:\n{sample}")
            
            result = parse_actual_reason(sample)
            print(f"\n[Output]:")
            print(json.dumps(result, ensure_ascii=False, indent=2))
            print("\n")

if __name__ == "__main__":
    run_test()
